/**
  * @brief This function handles USART2 global interrupt.
  */
void USART2_IRQHandler(void)
{
  /* USER CODE BEGIN USART2_IRQn 0 */
  /* USER CODE BEGIN USART1_IRQn 0 */
  if (RESET != __HAL_UART_GET_FLAG(&huart2, UART_FLAG_IDLE)) // 判读是否触发空闲中断
  {
    uint16_t temp = 0;
    __HAL_UART_CLEAR_IDLEFLAG(&huart2); // 清除空闲中断标志位
    HAL_UART_DMAStop(&huart2);          // 关闭MDA

    // 以下两行用来清除中断，软件清除空闲中断先读SR后读DR
    temp = huart2.Instance->SR;                                        // 清除SR状态寄存器
    temp = huart2.Instance->DR;                                        // 读取DR数据寄存器
    uint8_t data_length = 24 - __HAL_DMA_GET_COUNTER(&hdma_usart2_rx); // 获取接收的数据长度
    //    printf("Receive Data length = %d\r\n",data_length);
    //    printf("Receive Data:%s\r\n", usart1_recv);
  }

  /* USER CODE END USART2_IRQn 0 */
  HAL_UART_IRQHandler(&huart2);
  /* USER CODE BEGIN USART2_IRQn 1 */
  // HAL_UART_Receive_IT(&huart2 ,(uint8_t *)getBuffer,24);
  HAL_UART_Receive_DMA(&huart2, (uint8_t *)getBuffer, 24);
  /* USER CODE END USART2_IRQn 1 */
}

